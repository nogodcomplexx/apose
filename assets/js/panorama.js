// Ensure GSAP ScrollTrigger recalculates after images and fonts load on mobile
/**
 * Mobile Scroll Animations & Skill Bar Initializer
 * Guarantees luxury scroll reveals on phone screens without altering desktop logic
 */
function initMobileScrollAnimations() {
  if (typeof gsap === 'undefined') return;

  // 1. Mobile Title SplitText Reveal (phones and tablets <= 991px, native IntersectionObserver for Safari iOS & mobile)
  if (window.innerWidth <= 991 && typeof SplitText !== 'undefined') {
    const titles = gsap.utils.toArray('.title-anim');

    function animateTitle(elem) {
      if (elem.dataset.mobileAnimDone) return;
      elem.dataset.mobileAnimDone = 'true';
      try {
        if (elem._splitInstance && elem._splitInstance.chars && elem._splitInstance.chars.length > 0) {
          gsap.to(elem._splitInstance.chars, {
            duration: 0.8,
            x: 0,
            autoAlpha: 1,
            stagger: 0.025,
            ease: 'power2.out',
            clearProps: 'transform,opacity,visibility'
          });
        } else {
          elem.style.visibility = 'visible';
          elem.style.opacity = '1';
        }
      } catch (e) {
        elem.style.visibility = 'visible';
        elem.style.opacity = '1';
      }
    }

    titles.forEach((elem) => {
      if (elem.dataset.mobileAnimInit) return;
      elem.dataset.mobileAnimInit = 'true';
      try {
        const split = new SplitText(elem, {
          type: 'chars, words',
          lineThreshold: 0.5,
        });
        elem._splitInstance = split;
        // Set initial state: shifted and invisible until scrolled to
        gsap.set(split.chars, { autoAlpha: 0, x: 45 });
      } catch (err) {
        console.warn('SplitText mobile fallback:', err);
      }
    });

    if ('IntersectionObserver' in window) {
      const titleObserver = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            animateTitle(entry.target);
            titleObserver.unobserve(entry.target);
          }
        });
      }, {
        threshold: 0.05,
        rootMargin: '0px 0px -15px 0px'
      });

      titles.forEach(elem => titleObserver.observe(elem));
    }

    // Scroll and touch fallback: activates whenever any heading scrolls into the viewport
    const checkTitlesOnScroll = () => {
      titles.forEach((elem) => {
        if (elem.dataset.mobileAnimDone) return;
        const rect = elem.getBoundingClientRect();
        if (rect.top < window.innerHeight * 0.94 && rect.bottom > 0) {
          animateTitle(elem);
        }
      });
    };
    window.addEventListener('scroll', checkTitlesOnScroll, { passive: true });
    window.addEventListener('touchmove', checkTitlesOnScroll, { passive: true });
    setTimeout(checkTitlesOnScroll, 350);
    setTimeout(checkTitlesOnScroll, 800);
  }

  // 2. Skill Bars Counter & Fill Animation (Native IntersectionObserver + Scroll Fallback)
  const skillBars = document.querySelectorAll('.agency .skill-bar-single');
  if (skillBars.length > 0) {
    function animateBar(elem) {
      if (elem.dataset.barAnimDone) return;
      elem.dataset.barAnimDone = 'true';

      const w = elem.querySelector('.skill-bar-percent');
      const p = elem.querySelector('.percent-value');
      const wrapper = elem.querySelector('.skill-bar-wrapper');
      const targetPercent = wrapper ? (wrapper.getAttribute('data-percent') || '100%') : '100%';
      const targetNum = parseInt(targetPercent, 10) || 100;

      if (!w || !p) return;

      // Kill any paused/frozen GSAP tweens from plugins.js
      if (typeof gsap !== 'undefined') {
        gsap.killTweensOf([w, p]);
        
        const counter = { val: 0 };
        gsap.to(w, {
          width: targetPercent,
          duration: 1.6,
          ease: 'power2.out'
        });
        gsap.to(counter, {
          val: targetNum,
          duration: 1.6,
          ease: 'power2.out',
          onUpdate: function() {
            p.textContent = Math.round(counter.val) + '%';
          },
          onComplete: function() {
            p.textContent = targetPercent;
          }
        });
      } else {
        w.style.width = targetPercent;
        p.textContent = targetPercent;
      }
    }

    if ('IntersectionObserver' in window) {
      const barObserver = new IntersectionObserver((entries) => {
        entries.forEach((entry) => {
          if (entry.isIntersecting) {
            animateBar(entry.target);
            barObserver.unobserve(entry.target);
          }
        });
      }, {
        threshold: 0.1,
        rootMargin: '0px 0px -20px 0px'
      });

      skillBars.forEach(b => barObserver.observe(b));
    }

    // Scroll listener fallback for mobile touch
    const onScrollCheck = () => {
      skillBars.forEach(b => {
        if (b.dataset.barAnimDone) return;
        const rect = b.getBoundingClientRect();
        if (rect.top < window.innerHeight * 0.95 && rect.bottom > 0) {
          animateBar(b);
        }
      });
    };
    window.addEventListener('scroll', onScrollCheck, { passive: true });
    window.addEventListener('touchmove', onScrollCheck, { passive: true });
    // Also run once in case already visible
    setTimeout(onScrollCheck, 500);
  }

  // 3. Robust Ticker Fallback (ensures horizontal marquee never stacks)
  if (typeof jQuery !== 'undefined' && jQuery.fn && jQuery.fn.slick) {
    const $ticker = jQuery('.portfolio__text-slider');
    if ($ticker.length > 0 && !$ticker.hasClass('slick-initialized')) {
      $ticker.slick({
        slidesToShow: 2,
        slidesToScroll: 1,
        autoplay: true,
        autoplaySpeed: 0,
        speed: 10000,
        arrows: false,
        dots: false,
        pauseOnHover: false,
        cssEase: 'linear',
        variableWidth: true,
      });
    }
  }
}

